String _arbRender(
  AppLocalizations localizations,
  String key, [
  Map<String, Object> placeholders = const {},
]) {
  final language = localizations.localeName.split('_').first;
  var template = (language == 'bn' ? _arbBangla : _arbEnglish)[key]!;
  if (template.contains(', plural,')) {
    template = _selectPlural(template, placeholders);
  }
  for (final entry in placeholders.entries) {
    template = template.replaceAll('{${entry.key}}', '${entry.value}');
  }
  return template;
}

String _selectPlural(String template, Map<String, Object> values) {
  final headerEnd = template.indexOf(', plural,');
  if (headerEnd < 2 || !template.startsWith('{')) return template;
  final variable = template.substring(1, headerEnd).trim();
  final raw = values[variable];
  if (raw is! num) return template;
  final choices = <String, String>{};
  var cursor = headerEnd + ', plural,'.length;
  while (cursor < template.length - 1) {
    while (cursor < template.length && template[cursor].trim().isEmpty) {
      cursor++;
    }
    final open = template.indexOf('{', cursor);
    if (open < 0) break;
    final selector = template.substring(cursor, open).trim();
    var depth = 1;
    var close = open + 1;
    while (close < template.length && depth > 0) {
      if (template[close] == '{') depth++;
      if (template[close] == '}') depth--;
      close++;
    }
    if (depth != 0) return template;
    choices[selector] = template.substring(open + 1, close - 1);
    cursor = close;
  }
  return choices['=${raw.toInt()}'] ?? choices['other'] ?? template;
}
